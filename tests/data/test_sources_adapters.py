def write_fake_magnet_database(path: Path, *, material: str = "SYN") -> np.ndarray:
    """A pandas fixed-format HDF5 file with the upstream layout, filled with clearly synthetic rows."""
    import h5py

    rows = []
    for temperature in (25.0, 50.0):
        for frequency in (50e3, 100e3):
            for flux in (0.05, 0.1, 0.2):
                loss = 1e3 * (frequency / 50e3) ** 1.4 * (flux / 0.05) ** 2.5 * (1.0 + 0.2 * (temperature > 25.0))
                rows.append([frequency, flux, 0.0, -1.0, -1.0, temperature, loss])            # sinusoidal, zero bias
                rows.append([frequency, flux, 15.0, 0.5, 0.5, temperature, 1.3 * loss])        # triangular, biased
                rows.append([frequency, flux, 0.0, 0.3, 0.3, temperature, 1.1 * loss])         # trapezoidal (d0 = 0.2)
    values = np.asarray(rows, dtype=np.float64)
    columns = ["Frequency", "Flux_Density", "DC_Bias", "Duty_P", "Duty_N", "Temperature", "Power_Loss"]
    metadata = pickle.dumps({"info_core": INFO_CORE.replace("SYN", material), "info_setup": "2026-10-19 --- synthetic test setup --- no instrument",
                             "info_processing": "synthetic rows generated by the test suite"}, protocol=0).decode("latin-1")
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w") as handle:
        group = handle.create_group("dataframe")
        group.attrs["pandas_type"] = "frame"
        group.attrs["nblocks"] = 1
        group.attrs["metadata"] = metadata
        group.create_dataset("axis0", data=np.array(columns, dtype="S12"))
        group.create_dataset("axis1", data=np.arange(len(rows), dtype=np.int64))
        group.create_dataset("block0_items", data=np.array(columns, dtype="S12"))
        group.create_dataset("block0_values", data=values)
    return values


