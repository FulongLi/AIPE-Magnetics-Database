def write_mc2_files(directory: Path, *, samples: int = 128, rows: int = 4, pad_from: int | None = None, stem: str = "SYN_4") -> dict[str, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    t = np.arange(samples) / samples
    b = np.stack([0.1 * (k + 1) / rows * np.sin(2 * np.pi * t) for k in range(rows)])
    h = 25.0 * b
    if pad_from is not None:
        h = h.copy()
        h[:, pad_from:] = np.nan
    paths = {"B": directory / f"{stem}_B.csv", "H": directory / f"{stem}_H.csv", "T": directory / f"{stem}_T.csv"}
    np.savetxt(paths["B"], b, delimiter=",")
    np.savetxt(paths["H"], h, delimiter=",")
    np.savetxt(paths["T"], np.array([25.0, 50.0, 70.0, 25.0][:rows]).reshape(-1, 1), delimiter=",")
    return paths


