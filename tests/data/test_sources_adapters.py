def test_princeton_import_cycle_zip(tmp_path: Path):
    n, samples = 3, 128
    t = np.arange(samples) / samples
    b = np.stack([0.05 * (k + 1) * np.sin(2 * np.pi * t) for k in range(n)])
    h = np.stack([10.0 * (k + 1) * np.sin(2 * np.pi * t - 0.3) for k in range(n)])
    ts = np.array([1.0 / (100e3 * samples), 1.0 / (200e3 * samples), 1.0 / (50e3 * samples)])
    zip_path = tmp_path / "N87_cycle.zip"
    with zipfile.ZipFile(zip_path, "w") as archive:
        archive.writestr("b_cycle.csv", "\n".join(",".join(f"{v:.8g}" for v in row) for row in b) + "\n")
        archive.writestr("h_cycle.csv", "\n".join(",".join(f"{v:.8g}" for v in row) for row in h) + "\n")
        archive.writestr("sampling_time.csv", "\n".join(f"{v:.10g}" for v in ts) + "\n")
        archive.writestr("temperature.csv", "25\n50\n70\n")
        archive.writestr("test_info.txt", "synthetic zip written by the test suite\n")
    adapter = PrincetonMagnetAdapter(LocalCache(tmp_path / "cache"))
    result = adapter.import_cycle_zip(zip_path, destination_dir=tmp_path / "out", material="N87")
    records = _validated(result)
    waveform = next(r for r in records if r.kind == "waveform_dataset")
    props = waveform.typed_properties()
    assert props.n_sequences == 3 and props.samples_per_sequence == 128 and props.timebase == "uniform_per_period"
    data = WaveformStore().read(next(p for p in result.written if p.endswith(".h5")))
    assert np.allclose(data.conditions["frequency"], [100e3, 200e3, 50e3]) and np.allclose(data.conditions["temperature"], [298.15, 323.15, 343.15])
    assert data.array_units == {"field": "A/m", "flux_density": "T"}
    assert result.source_sha256 == sha256_file(zip_path) and waveform.evidence[1].kind == "measurement"
    with zipfile.ZipFile(tmp_path / "bad.zip", "w") as archive:
        archive.writestr("b_cycle.csv", "0,1,2\n")
        archive.writestr("h_cycle.csv", "0,1,2\n")
        archive.writestr("sampling_time.csv", "1e-6\n")
        archive.writestr("temperature.csv", "25\n")
    with pytest.raises(DataIntegrityError, match="samples per row"):
        adapter.import_cycle_zip(tmp_path / "bad.zip", destination_dir=tmp_path / "out2", material="N87")
    with pytest.raises(InvalidInputError):
        adapter.import_cycle_zip(zip_path, destination_dir=tmp_path / "out3", material="XYZ")


