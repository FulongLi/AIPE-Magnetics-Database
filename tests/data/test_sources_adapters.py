def _validated(result) -> list[MagneticRecord]:
    """Re-load every written record, validate it (schema + semantics + cross-references) and check the shared invariants."""
    records = [MagneticRecord.model_validate(load(p)) for p in result.written if p.endswith(".json")]
    assert records and {r.id for r in records} <= {r.id for r in result.records}
    for record in records:
        assert validate_record(record.to_json_dict()) == [], record.id
        assert all(e.review_status == "unreviewed" for e in record.evidence)
        assert len(record.extensions[SOURCES_EXTENSION]["commit"]) == 40 and record.extensions[SOURCES_EXTENSION]["license"] == record.license
        if "identity-only" not in record.tags:
            assert record.extensions["aipe.import"]["source_sha256"] and record.extensions["aipe.import"]["importer"].startswith("aipe.magnetics.sources.")
    assert validate_catalogue(records) == []
    return records


def _load_example(name: str):
    path = EXAMPLES / f"{name}.py"
    spec = importlib.util.spec_from_file_location(f"aipe_example_{name}", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


